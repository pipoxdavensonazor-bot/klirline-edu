'use strict';
// Couche base abstraite : même interface asynchrone pour SQLite (développement, tests rapides) et PostgreSQL (production).
//   await db.get(sql, ...params)   première ligne ou undefined
//   await db.all(sql, ...params)   toutes les lignes
//   await db.run(sql, ...params)   { changes }
//   await db.insert(sql, ...params) identifiant créé (ajoute RETURNING id)
//   await db.tx(async (t) => ...)  transaction (point de sauvegarde si déjà dans une transaction)
//   await db.asSchool(schoolId, async (t) => ...)  requête d'un utilisateur connecté : en PostgreSQL, transaction sous le
//     rôle noria_app avec app.school_id réglé, donc soumise aux politiques RLS. En SQLite, pas de RLS : le cloisonnement
//     repose sur les clauses de policy.js (toujours appliquées, quelle que soit la base).
//   await db.asMinistry(accountId, async (t) => ...)  requête d'un compte du ministère (bloc 6) : en PostgreSQL, rôle
//     noria_ministere (lecture par colonnes, politiques « ministere_lecture » dédiées, aucun contournement global) avec
//     app.ministere_id réglé. En SQLite : requêtes explicites de src/ministere.js (colonnes choisies, lecture seule).
// Le SQL s'écrit avec des « ? » ; ils deviennent $1, $2… pour PostgreSQL. Règle : ne jamais attendre une entrée-sortie
// externe (hachage, réseau) dans une transaction SQLite, pour qu'aucune autre requête ne s'y intercale.
const fs = require('node:fs');
const path = require('node:path');

const MIGRATIONS = path.join(__dirname, '..', 'migrations');
const PK = { sqlite: 'INTEGER PRIMARY KEY', pg: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' };

function toPg(sql) { let i = 0; return sql.replace(/\?/g, () => `$${++i}`); }

function migrationList(dialect) {
  const files = fs.readdirSync(MIGRATIONS).filter((f) => /^\d{3}_.+\.sql$/.test(f));
  const versions = [...new Set(files.map((f) => f.slice(0, 3)))].sort();
  return versions.map((v) => {
    const common = files.find((f) => f.startsWith(v) && /^\d{3}_[^.]+\.sql$/.test(f));
    const own = files.find((f) => f.startsWith(v) && f.endsWith(`.${dialect}.sql`));
    if (!common && !own) return null;
    const sql = [common, own].filter(Boolean).map((f) => fs.readFileSync(path.join(MIGRATIONS, f), 'utf8')).join('\n');
    return { version: v, name: (common || own).replace(/(\.(sqlite|pg))?\.sql$/, ''), sql: sql.replace(/\{\{PK\}\}/g, PK[dialect]) };
  }).filter(Boolean);
}

/* ---------------- SQLite ---------------- */
function sqliteDb(file) {
  const Database = require('better-sqlite3');
  const raw = new Database(file);
  raw.pragma('foreign_keys = ON');
  if (file !== ':memory:') raw.pragma('journal_mode = WAL');
  let depth = 0;
  const api = {
    kind: 'sqlite', raw,
    async get(sql, ...p) { return raw.prepare(sql).get(...p); },
    async all(sql, ...p) { return raw.prepare(sql).all(...p); },
    async run(sql, ...p) { return { changes: raw.prepare(sql).run(...p).changes }; },
    async insert(sql, ...p) { return raw.prepare(`${sql} RETURNING id`).get(...p).id; },
    async exec(sql) { raw.exec(sql); },
    async tx(fn) {
      const sp = `sp${++depth}`;
      raw.exec(`SAVEPOINT ${sp}`);
      try { const r = await fn(api); raw.exec(`RELEASE ${sp}`); return r; }
      catch (e) { raw.exec(`ROLLBACK TO ${sp}`); raw.exec(`RELEASE ${sp}`); throw e; }
      finally { depth--; }
    },
    async asSchool(_schoolId, fn) { return fn(api); },
    async asMinistry(_accountId, fn) { return fn(api); },
    async close() { raw.close(); },
  };
  return api;
}

/* ---------------- PostgreSQL ---------------- */
function pgDb(url) {
  const pg = require('pg');
  pg.types.setTypeParser(20, (v) => Number(v)); // BIGINT (COUNT, at_ms) → nombre
  const pool = new pg.Pool({ connectionString: url, max: Number(process.env.NORIA_PG_POOL || 10) });
  const wrap = (q, inTx) => {
    let depth = 0;
    const api = {
      kind: 'pg', pool,
      async get(sql, ...p) { return (await q.query(toPg(sql), p)).rows[0]; },
      async all(sql, ...p) { return (await q.query(toPg(sql), p)).rows; },
      async run(sql, ...p) { return { changes: (await q.query(toPg(sql), p)).rowCount }; },
      async insert(sql, ...p) { return (await q.query(`${toPg(sql)} RETURNING id`, p)).rows[0].id; },
      async exec(sql) { await q.query(sql); },
      async tx(fn) {
        if (!inTx) return transaction(null, fn);
        const sp = `sp${++depth}`;
        await q.query(`SAVEPOINT ${sp}`);
        try { const r = await fn(api); await q.query(`RELEASE SAVEPOINT ${sp}`); return r; }
        catch (e) { await q.query(`ROLLBACK TO SAVEPOINT ${sp}`); throw e; }
        finally { depth--; }
      },
      async asSchool(schoolId, fn) { return inTx ? fn(api) : transaction({ role: 'noria_app', key: 'app.school_id', value: schoolId }, fn); },
      async asMinistry(accountId, fn) {
        if (inTx) throw new Error('asMinistry : jamais dans une transaction déjà ouverte'); // sinon droits du système
        return transaction({ role: 'noria_ministere', key: 'app.ministere_id', value: accountId }, fn);
      },
      async close() { await pool.end(); },
    };
    return api;
  };
  // scope : null (connexion système) ou { role, key, value } (rôle soumis à la RLS et réglage de transaction).
  async function transaction(scope, fn) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      if (scope && scope.value != null) {
        await client.query(`SET LOCAL ROLE ${scope.role === 'noria_ministere' ? 'noria_ministere' : 'noria_app'}`);
        await client.query('SELECT set_config($1, $2, true)', [scope.key === 'app.ministere_id' ? 'app.ministere_id' : 'app.school_id', String(scope.value)]);
      }
      const r = await fn(wrap(client, true));
      await client.query('COMMIT');
      return r;
    } catch (e) { await client.query('ROLLBACK').catch(() => {}); throw e; }
    finally { client.release(); }
  }
  return wrap(pool, false);
}

async function migrate(db) {
  const dialect = db.kind;
  // Une seule transaction : en PostgreSQL, le verrou consultatif empêche deux processus de migrer en même temps.
  return db.tx(async (t) => {
    if (dialect === 'pg') await t.exec('SELECT pg_advisory_xact_lock(727001)');
    await t.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, name TEXT NOT NULL, applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)');
    const done = new Set((await t.all('SELECT version FROM schema_migrations')).map((r) => r.version));
    const applied = [];
    for (const m of migrationList(dialect)) {
      if (done.has(m.version)) continue;
      await t.exec(m.sql);
      await t.run('INSERT INTO schema_migrations (version, name) VALUES (?,?)', m.version, m.name);
      applied.push(m.version);
    }
    return applied;
  });
}

// url : chemin SQLite (ou ':memory:'), ou postgres://… ; migre avant de rendre la main.
async function openStore(url = ':memory:') {
  const db = /^postgres(ql)?:\/\//.test(url) ? pgDb(url) : sqliteDb(url);
  await migrate(db);
  return db;
}

module.exports = { openStore, migrate, migrationList, toPg };
